"""Pre-render the display fonts into C tables for the ESP32 firmware.

    python3 esp32/tools/gen_fonts.py            # writes esp32/main/fonts/fonts_data.c

The Python deck rasterises text at runtime with Pillow: its bundled default
font (Aileron Regular) for text and the repo's NotoEmoji.ttf for the icons.
The ESP32 has no FreeType, so every size the renderer ever asks for is
rendered here, once, into 4-bit coverage bitmaps and compiled in. Keeping
the same fonts (and Pillow's own metrics) is what makes the two devices draw
the same screens.

Sizes mirror src/huckdeck/feedback/display.py:
  text   10-15 (pane labels, overlay sub), 18/22/26/30/34 (pane values,
         overlay title), 40 (ticker), and every even size 16-44 (session timer)
  emoji  40 (ticker) and every even size 16-44 (session timer)

Needs Pillow (`pip install pillow`); Pillow 10.1+ bundles Aileron.
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import ImageFont

ROOT = Path(__file__).resolve().parents[2]
EMOJI_TTF = ROOT / "src" / "huckdeck" / "feedback" / "fonts" / "NotoEmoji.ttf"
OUT = ROOT / "esp32" / "main" / "fonts" / "fonts_data.c"

TEXT_SIZES = sorted({10, 11, 12, 13, 14, 15, 18, 22, 26, 30, 34, 40} | set(range(16, 45, 2)))
EMOJI_SIZES = sorted({40} | set(range(16, 45, 2)))
TEXT_CHARS = [chr(c) for c in range(0x20, 0x7F)]
EMOJI_CHARS = ["💧", "💩", "🤱", "😴", "🍼"]  # DIAPER_EMOJI / NURSING / SLEEP / BOTTLE in display.py


def text_font(size: int):
    return ImageFont.load_default(size=size)


def emoji_font(size: int):
    font = ImageFont.truetype(str(EMOJI_TTF), size)
    font.set_variation_by_axes([600])  # same weight as the Python deck
    return font


def render_glyph(font, ch: str):
    """(advance_q6, width, height, left, top_from_baseline, 4bpp rows)."""
    advance = font.getlength(ch)
    mask, (left, top) = font.getmask2(ch, mode="L", anchor="ls")
    w, h = mask.size
    pixels = list(mask) if w and h else []
    rows = []
    for y in range(h):
        row = pixels[y * w:(y + 1) * w]
        packed = []
        for x in range(0, w, 2):
            a = row[x] >> 4
            b = (row[x + 1] >> 4) if x + 1 < w else 0
            packed.append((a << 4) | b)
        rows.append(packed)
    return int(round(advance * 64)), w, h, left, top, rows


def emit_font(out: list[str], name: str, font, chars: list[str], size: int) -> None:
    ascent, descent = font.getmetrics()
    glyphs = []
    bitmap: list[int] = []
    for ch in chars:
        adv, w, h, left, top, rows = render_glyph(font, ch)
        glyphs.append((ord(ch), adv, w, h, left, top, len(bitmap)))
        for row in rows:
            bitmap.extend(row)
    out.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(bitmap), 24):
        out.append("    " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
    if not bitmap:
        out.append("    0,")
    out.append("};")
    out.append(f"static const glyph_t {name}_glyphs[] = {{")
    for cp, adv, w, h, left, top, off in glyphs:
        out.append(f"    {{0x{cp:x}, {adv}, {w}, {h}, {left}, {top}, {off}}},")
    out.append("};")
    out.append(
        f"static const font_t {name} = {{{size}, {ascent}, {descent}, {len(glyphs)}, {name}_glyphs, {name}_bits}};"
    )
    out.append("")


def main() -> None:
    out = [
        "/* Generated by esp32/tools/gen_fonts.py — do not edit. */",
        "#include \"fonts.h\"",
        "",
    ]
    for size in TEXT_SIZES:
        emit_font(out, f"text_{size}", text_font(size), TEXT_CHARS, size)
    for size in EMOJI_SIZES:
        emit_font(out, f"emoji_{size}", emoji_font(size), EMOJI_CHARS, size)
    out.append("const font_t *const text_fonts[] = {" + ", ".join(f"&text_{s}" for s in TEXT_SIZES) + "};")
    out.append(f"const int text_fonts_count = {len(TEXT_SIZES)};")
    out.append("const font_t *const emoji_fonts[] = {" + ", ".join(f"&emoji_{s}" for s in EMOJI_SIZES) + "};")
    out.append(f"const int emoji_fonts_count = {len(EMOJI_SIZES)};")
    out.append("")
    OUT.write_text("\n".join(out))
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
